CREATE TABLE members (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, username VARCHAR(40) NOT NULL UNIQUE,
 password_hash VARCHAR(100) NOT NULL, pen_name VARCHAR(40) NOT NULL,
 bio VARCHAR(300) NOT NULL DEFAULT '', role VARCHAR(12) NOT NULL DEFAULT 'MEMBER',
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE invitations (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, code_hash CHAR(64) NOT NULL UNIQUE,
 label VARCHAR(80) NOT NULL, max_uses INT NOT NULL DEFAULT 1, used_count INT NOT NULL DEFAULT 0,
 active BOOLEAN NOT NULL DEFAULT TRUE, expires_at TIMESTAMP NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE tags (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, name VARCHAR(30) NOT NULL UNIQUE,
 description VARCHAR(300) NOT NULL DEFAULT '', is_activity BOOLEAN NOT NULL DEFAULT FALSE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
