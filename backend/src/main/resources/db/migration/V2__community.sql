CREATE TABLE works (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, author_id BIGINT NOT NULL,
 title VARCHAR(100) NOT NULL, genre VARCHAR(30) NOT NULL DEFAULT '其他',
 excerpt VARCHAR(240) NOT NULL DEFAULT '', body MEDIUMTEXT NOT NULL,
 plain_text MEDIUMTEXT NOT NULL, cover VARCHAR(100) NOT NULL DEFAULT '',
 status VARCHAR(16) NOT NULL DEFAULT 'DRAFT', featured BOOLEAN NOT NULL DEFAULT FALSE, is_demo BOOLEAN NOT NULL DEFAULT FALSE,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 published_at TIMESTAMP NULL, CONSTRAINT fk_work_author FOREIGN KEY(author_id) REFERENCES members(id),
 INDEX idx_works_public(status,published_at), INDEX idx_works_author(author_id,status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE work_tags (work_id BIGINT NOT NULL, tag_id BIGINT NOT NULL,
 PRIMARY KEY(work_id,tag_id), FOREIGN KEY(work_id) REFERENCES works(id), FOREIGN KEY(tag_id) REFERENCES tags(id));
CREATE TABLE reactions (member_id BIGINT NOT NULL, work_id BIGINT NOT NULL, kind VARCHAR(12) NOT NULL,
 PRIMARY KEY(member_id,work_id,kind), FOREIGN KEY(member_id) REFERENCES members(id), FOREIGN KEY(work_id) REFERENCES works(id));
CREATE TABLE comments (id BIGINT PRIMARY KEY AUTO_INCREMENT, member_id BIGINT NOT NULL, work_id BIGINT NOT NULL,
 body VARCHAR(1000) NOT NULL, visible BOOLEAN NOT NULL DEFAULT TRUE, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(member_id) REFERENCES members(id), FOREIGN KEY(work_id) REFERENCES works(id));
CREATE TABLE media_files (id CHAR(36) PRIMARY KEY, owner_id BIGINT NOT NULL, original_name VARCHAR(200) NOT NULL,
 file_path VARCHAR(100) NOT NULL, mime_type VARCHAR(80) NOT NULL, size_bytes BIGINT NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, FOREIGN KEY(owner_id) REFERENCES members(id));
CREATE TABLE work_media (work_id BIGINT NOT NULL, media_id CHAR(36) NOT NULL,
 PRIMARY KEY(work_id,media_id), FOREIGN KEY(work_id) REFERENCES works(id), FOREIGN KEY(media_id) REFERENCES media_files(id));
