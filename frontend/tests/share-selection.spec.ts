import {test,expect} from '@playwright/test'

test('article share selects blocks and sentences, enforcing both limits',async({page})=>{
 const body='<p>第一句。第二句！第三句。</p>'+Array.from({length:11},(_,i)=>`<p>第${i+1}块。</p>`).join('')+`<p>${'满'.repeat(500)}</p><p>${'长'.repeat(501)}</p>`
 await page.route('**/api/**',async route=>{
  const path=new URL(route.request().url()).pathname
  if(path==='/api/public/works/1')return route.fulfill({json:{id:1,title:'测试文章',authorId:1,authorName:'作者',displayByline:'作者',genre:'散文',wordCount:600,collection:null,status:'PUBLISHED',body,excerpt:'旧摘要',tags:[],likes:0,comments:0}})
  if(path==='/api/public/works/1/comments')return route.fulfill({json:[]})
  if(path==='/api/public/traffic')return route.fulfill({json:{online:0,visitors:0}})
  if(path==='/api/public/site')return route.fulfill({json:{name:'海燕传信'}})
  if(path==='/api/auth/me')return route.fulfill({json:null})
  return route.fulfill({json:{}})
 })
 await page.setViewportSize({width:390,height:844});await page.goto('/#/work/1')
 await page.getByRole('button',{name:'分享',exact:true}).click()
 const dialog=page.getByRole('dialog',{name:'分享文章'})
 await expect(dialog.locator('.share-preview img')).toBeVisible()
 await dialog.getByRole('button',{name:'第二句！',exact:true}).click()
 await expect(dialog.locator('.share-excerpts-heading')).toContainText('1/10 块 · 4/500 字')
 await dialog.locator('.share-block').nth(0).getByRole('button',{name:'选择整块'}).click()
 await expect(dialog.locator('.share-excerpts-heading')).toContainText('1/10 块 · 12/500 字')
 for(let i=1;i<=9;i++)await dialog.locator('.share-block').nth(i).getByRole('button',{name:'选择整块'}).click()
 await expect(dialog.locator('.share-excerpts-heading')).toContainText('10/10 块')
 await dialog.locator('.share-block').nth(10).getByRole('button',{name:'选择整块'}).click()
 await expect(dialog.getByRole('alert')).toContainText('最多选择 10 个文字块、500 字')
 await dialog.locator('.share-block').nth(0).getByRole('button',{name:'取消整块'}).click()
 await dialog.locator('.share-block').last().getByRole('button',{name:'选择整块'}).click()
 await expect(dialog.getByRole('alert')).toContainText('最多选择 10 个文字块、500 字')
 await expect(dialog.locator('.share-excerpts-heading')).toContainText('9/10 块')
 await expect(dialog.locator('.share-preview img')).toBeVisible()
 await dialog.getByRole('button',{name:'关闭分享卡片'}).click()
 await page.getByRole('button',{name:'分享',exact:true}).click()
 const reopened=page.getByRole('dialog',{name:'分享文章'})
 await reopened.locator('.share-block').nth(12).getByRole('button',{name:'选择整块'}).click()
 await expect(reopened.locator('.share-excerpts-heading')).toContainText('1/10 块 · 500/500 字')
 await expect(reopened.locator('.share-preview img')).toBeVisible()
 expect(await reopened.locator('.share-preview img').evaluate((image:HTMLImageElement)=>image.naturalHeight)).toBeGreaterThan(1400)
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy()
})
